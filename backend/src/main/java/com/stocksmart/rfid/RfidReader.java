package com.stocksmart.rfid;

import java.time.Instant;
import java.util.List;

/**
 * RFID reader abstraction (Day 5).
 *
 * <p>Device-specific transport is kept behind this interface: a physical
 * reader bridge and the built-in simulator both surface reads as
 * {@link RfidRead} values, and {@code RfidService} applies the same
 * validation, mapping and audit rules regardless of source.
 *
 * <p>The built-in implementation is {@link SimulatedRfidReader}; no physical
 * RFID hardware has been integrated or tested in this phase.
 */
public interface RfidReader {

    /** Human-readable reader name surfaced on read events. */
    String readerName();

    /** True when reads are generated by the simulator, never by hardware. */
    boolean simulated();

    /**
     * Produce the reads currently visible to this reader.
     *
     * @param epcCodeOrNull optional requested tag; the simulator echoes it
     *                      when supplied, or picks a registered active tag
     *                      when null
     * @return zero or more reads (never null)
     */
    List<RfidRead> scan(String epcCodeOrNull);
}
